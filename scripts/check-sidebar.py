"""Check the built sidebar: groups with an overview link render as split controls, at the top level
(with the large heading label) and nested (docs/sidebar.md). Run after `npm run build`."""
from pathlib import Path
import re,sys
root=Path(sys.argv[1]).resolve() if len(sys.argv)>1 else Path(__file__).resolve().parents[1]/'dist'
errors=[]
def check(cond,msg):
 if not cond:errors.append(msg)
def sidebar(page):
 html=(root/page.strip('/')/'index.html').read_text(encoding='utf-8')
 m=re.search(r'<sl-sidebar-state-persist.*?</sl-sidebar-state-persist>',html,re.S)
 assert m,f'{page}: no sidebar';return m.group(0)
def split(html,label):
 m=re.search(r'<li class="split-group[^"]*">\s*<div class="split-row[^"]*">\s*(<a [^>]*>)\s*<span[^>]*>'+re.escape(label)+r'</span>.*?</a>\s*(<button [^>]*>).*?</button>\s*</div>\s*(<details [^>]*>)',html,re.S)
 return m and m.groups()
def attr(tag,name):
 m=re.search(r'\s'+name+r'="([^"]*)"',tag);return m and m.group(1)
s=sidebar('/features/combat/')
# Top level: sections with an overview page are split controls whose label keeps the large heading
# style; the overview is not listed again as a child.
TOP=[('Fundamentals','/fundamentals/'),('Reference','/reference/'),('Features','/features/'),('Guides','/guides/'),('Recipes','/recipes/')]
for label,href in TOP:
 m=re.search(r'<li class="split-group top-split[^"]*">\s*<div class="split-row[^"]*">\s*<a href="'+re.escape(href)+r'"[^>]*class="split-link[^"]*"[^>]*>\s*<span class="large[^"]*">'+label+'</span>',s)
 check(m,f'top-level section {label} is not a split control with a large label linking {href}')
 check(s.count(f'href="{href}"')==1,f'{href} is listed again besides the top-level split label')
check('>Overview</span>' not in s and '>Features Overview</span>' not in s,'a redundant Overview child is still listed')
for label,href in [('Wiki archive','/wiki/'),('About these docs','/about/')]:
 check(re.search(r'<a href="'+re.escape(href)+r'"[^>]*class="large[^"]*"',s),f'{label} is no longer a plain top-level link')
check(not re.search(r'<li class="split-group(?! top-split)[^"]*">[\s\S]{0,300}?<span class="large',s),'a nested split group has a large label')
# Split groups.
for label,href in [('Combat','/features/combat/'),('Categories','/categories/'),('Constants','/constants/'),('Types','/types/'),('Flow control','/controls/')]:
 g=split(s,label)
 check(g,f'{label} is not a split group')
 if not g:continue
 a,b,d=g
 check(attr(a,'href')==href,f'{label} label links to {attr(a,"href")}, expected {href}')
 check(attr(b,'type')=='button' and attr(b,'aria-controls')==attr(d,'id') and attr(b,'aria-controls'),f'{label} toggle aria-controls does not match its details')
 check(attr(b,'aria-expanded') in ('true','false') and re.match(r'(Expand|Collapse) '+re.escape(label)+'$',attr(b,'aria-label') or ''),f'{label} toggle lacks aria-expanded or name')
# Current overview page: label current, group open, no Overview child.
a,b,d=split(s,'Combat')
check(attr(a,'aria-current')=='page' and attr(b,'aria-expanded')=='true' and re.search(r'\sopen[\s>]',d),'Combat is not current and open on its overview page')
ref=s[s.index('>Reference</span>'):s.index('>Features</span>')]
for href in ['/features/combat/','/categories/','/constants/','/types/','/controls/']:
 check((s if href.startswith('/features/') else ref).count(f'href="{href}"')==1,f'{href} is listed again besides the split label (Overview child not removed)')
# A nested group without an overview link stays a single toggle, not large.
# A category group with its own category is a split control whose label opens that category
# (Effects › Effects, Avatars › Avatar Target); groups without one stay plain toggles.
check(re.search(r'<a href="/categories/effects/"[^>]*split-link',ref),'Categories › Effects is not a split control opening the Effects category')
check(re.search(r'<a href="/categories/avatar/"[^>]*split-link',ref),'Categories › Avatars is not a split control opening Avatar Target')
check(not re.search(r'<a href="/features/[a-z-]+/"[^>]*split-link',ref),'a Categories group links a feature page')
# A feature with a single category is a plain link under Categories, not a one-item collapsible.
check(not re.search(r'<span class="group-label[^"]*">\s*<span[^>]*>Combat</span>',ref),'Categories › Combat is a one-item collapsible')
check('href="/categories/combat/"' in ref,'Categories › Combat is not a direct category link')
# Deep page: the closest entry (Combat's overview) is current through src/routeData.ts or a sub-page link.
sub=sidebar('/features/combat/combat-log/')
a,b,d=split(sub,'Combat')
check(attr(b,'aria-expanded')=='true' and attr(a,'aria-current') is None,'Combat is not open (or wrongly current) on a sub-page')
# A guide with sub-pages (an autogenerated directory with an index.mdx) is a nested split control
# labelled by its frontmatter attribute value, not the directory name; its sub-page sits under the chevron.
g=split(s,'Constraining rotations')
check(g and attr(g[0],'href')=='/guides/constraining-rotations/','Guides › Constraining rotations is not a split group linking the guide')
check('>constraining-rotations</span>' not in s,'the guide group is labelled with its directory name')
guides=s[s.rindex('<li',0,s.index('>Guides</span>')):s.rindex('<li',0,s.index('>Recipes</span>'))]
check(guides.count('href="/guides/constraining-rotations/"')==1,'the guide is listed again besides its split label')
check('href="/guides/constraining-rotations/turret/"' in guides,'Turret rotation is not listed under the guide')
t=sidebar('/guides/constraining-rotations/turret/')
g=split(t,'Constraining rotations')
check(g and attr(g[1],'aria-expanded')=='true' and re.search(r'<a href="/guides/constraining-rotations/turret/"[^>]*aria-current="page"',t),'the guide group is not open with Turret rotation current on the sub-page')
# Fundamentals has its own pages (src/content/docs/fundamentals/), never Reference pages.
def section(html,start,end):
 at=lambda l:html.rindex('<li',0,html.index(f'>{l}</span>'))
 return html[at(start):at(end)]
fund=section(s,'Fundamentals','Reference')
hrefs=re.findall(r'href="([^"]*)"',fund)
check('/fundamentals/' in hrefs,'Fundamentals lacks its overview')
check(len(hrefs)>2,'Fundamentals has no concept pages')
for h in hrefs:check(h.startswith('/fundamentals/'),f'Fundamentals links outside /fundamentals/: {h}')
# Reference pages open in Reference, Fundamentals pages in Fundamentals.
def current(page):
 h=sidebar(page);m=re.search(r'<a [^>]*aria-current="page"[^>]*>',h)
 check(m,f'{page}: no current sidebar entry')
 if not m:return None
 i=m.start();at=lambda l:h.rindex('<li',0,h.index(f'>{l}</span>'))
 return 'Fundamentals' if at('Fundamentals')<=i<at('Reference') else 'Reference' if i<at('Features') else 'other'
for page in ['/types/','/types/integer/','/controls/','/controls/if/']:
 check(current(page)=='Reference',f'{page} does not mark a Reference entry as current')
for page in ['/fundamentals/','/fundamentals/types/']:
 check(current(page)=='Fundamentals',f'{page} does not mark a Fundamentals entry as current')
if errors:
 print('\n'.join(errors));sys.exit(1)
print('Sidebar OK: top-level and nested groups with an overview page are split controls.')

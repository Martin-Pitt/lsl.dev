/**
 * Feature index, derived from the hand-written pages in src/content/docs/features/*.mdx.
 *
 *   import { loadFeatures } from './scripts/feature-index.mjs'   (astro.config.mjs: sidebar)
 *   node scripts/feature-index.mjs                               (rewrites src/data/feature-clusters.json)
 *
 * src/data/feature-clusters.json is a GENERATED compatibility index for code that still imports
 * it (src/lib/catalog.ts). New code should use src/lib/features.ts, which reads the MDX directly.
 * `npm run test:data` fails if the JSON is out of date.
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { parseFeatureMdx, withSubpages } from '../src/lib/feature-mdx.mjs';

const root = new URL('../', import.meta.url);
const dir = new URL('src/content/docs/features/', root);

/** All feature pages in slug order, each with its sub-pages (features/<id>/<topic>.mdx) merged in. */
export function loadFeatures() {
	return readdirSync(dir)
		.filter(f => f.endsWith('.mdx'))
		.sort()
		.map(f => {
			const id = f.slice(0, -4);
			const subdir = new URL(`${id}/`, dir);
			const subs = existsSync(subdir)
				? readdirSync(subdir).filter(s => s.endsWith('.mdx')).map(s => parseFeatureMdx(s.slice(0, -4), readFileSync(new URL(s, subdir), 'utf-8')))
				: [];
			return withSubpages(parseFeatureMdx(id, readFileSync(new URL(f, dir), 'utf-8')), subs);
		});
}

export function compatIndex(features = loadFeatures()) {
	return {
		$comment: 'GENERATED by `node scripts/feature-index.mjs` from src/content/docs/features/*.mdx. Do not edit; edit the MDX pages instead.',
		features: features.map(f => ({
			id: f.id, title: f.title, description: f.description, categories: f.categories, related: f.related,
			sections: [{ title: f.title, items: f.items, groups: f.groups }],
		})),
		// The site has not been deployed, so retired slugs are not redirected. Kept empty for older code.
		redirects: {},
	};
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const out = new URL('src/data/feature-clusters.json', root);
	writeFileSync(out, JSON.stringify(compatIndex(), null, '\t') + '\n');
	console.log(`wrote ${fileURLToPath(out)}`);
}

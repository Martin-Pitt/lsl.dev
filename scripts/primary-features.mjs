// @ts-check
/**
 * Primary feature of every public API (rules: src/lib/primary-feature-rules.mjs).
 *
 *   node scripts/primary-features.mjs                            writes data/reports/primary-features.md
 *   node scripts/primary-features.mjs --check                    fails if the report is out of date
 *   node scripts/primary-features.mjs --json [overrides.json]    prints { name: choice } (used by the tests)
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
import { loadFeatures } from './feature-index.mjs';
import { featureScore, choosePrimary } from '../src/lib/primary-feature-rules.mjs';

const root = new URL('../', import.meta.url);
const read = (/** @type {string} */ p) => readFileSync(new URL(p, root), 'utf-8');
const dir = 'src/content/docs/features/';

/** @param {string} [overridesPath] path to an overrides JSON file (defaults to the site's) */
export function computeAll(overridesPath) {
	const catalog = JSON.parse(read('src/data/catalog.json'));
	const ovUrl = overridesPath ? pathToFileURL(resolve(overridesPath)) : new URL('src/data/primary-feature-overrides.json', root);
	const overrides = JSON.parse(readFileSync(ovUrl, 'utf-8')).overrides ?? {};
	const features = loadFeatures();
	const scores = features.map(f => {
		const sub = new URL(`${dir}${f.id}/`, root);
		const subs = existsSync(sub) ? readdirSync(sub).filter(s => s.endsWith('.mdx')).sort().map(s => readFileSync(new URL(s, sub), 'utf-8')) : [];
		return featureScore(f, read(`${dir}${f.id}.mdx`), subs);
	});
	/** @type {Record<string, any>} */
	const out = {};
	for (const kind of ['functions', 'events', 'constants'])
		for (const e of catalog[kind]) out[e.name] = { kind, categories: e.categories ?? [], groups: e.groups ?? [], ...choosePrimary(e, scores, overrides) };
	return { out, features, catalog };
}

/** @param {boolean} check compare with the file instead of writing it */
function report(check = false) {
	const { out, features, catalog } = computeAll();
	const title = new Map(features.map(f => [f.id, f.title]));
	const label = new Map(catalog.categories.map((/** @type {any} */ c) => [c.id, c.label]));
	const rows = Object.entries(out);
	const count = (/** @type {(c: any) => boolean} */ fn) => rows.filter(([, c]) => fn(c)).length;
	const tierOf = (/** @type {any} */ c) => c.reason.split(' ')[0];
	const fallback = (/** @type {any} */ c) =>
		c.kind === 'constants' && c.groups[0] ? `group ${c.groups[0]}` : c.categories[0] ? `category ${label.get(c.categories[0]) ?? c.categories[0]}` : 'section only';
	const L = [
		'# Primary features',
		'',
		'GENERATED by `node scripts/primary-features.mjs`. The primary feature is the middle breadcrumb on API pages',
		'(Functions › Combat › llDamage) and the sidebar entry marked current. Rules: `src/lib/primary-feature-rules.mjs`.',
		'To change a choice, add `"<API name>": "<feature id>"` to `overrides` in `src/data/primary-feature-overrides.json`, then rerun.',
		'',
		'Tiers, strongest first: **main** = in a signature or API list in a main section, or linked in Scripting Details;',
		'**subpage** = the same on a feature sub-page; **group** = the constant\'s group is in `<ConstantGroups>`;',
		'**prose** = linked in a main section; **minor** = only in Additional / Related, or a prose link to the group;',
		'**category** = not mentioned, but the feature owns one of the API\'s categories.',
		'Ties within a tier go to the feature that owns one of the API\'s categories, then the smallest feature, then the id.',
		'',
		'## Counts',
		'',
		`- APIs: ${rows.length}`,
		`- With a primary feature: ${count(c => c.feature)}`,
		...['override', 'main', 'subpage', 'group', 'prose', 'minor', 'category'].map(t => `  - ${t}: ${count(c => c.feature && tierOf(c) === t)}`),
		`- No feature (breadcrumb falls back to the category or constant group): ${count(c => !c.feature)}`,
		`  - with neither category nor group (breadcrumb is section › name): ${count(c => !c.feature && !c.categories.length && !c.groups.length)}`,
		`- Ambiguous (tied on tier and category ownership, decided by size or id): ${count(c => c.tied.length)}`,
		'',
		'## Ambiguous choices',
		'',
		'| API | Chosen | Tier | Also tied | Decided by |',
		'| --- | --- | --- | --- | --- |',
		...rows.filter(([, c]) => c.tied.length).map(([n, c]) => `| ${n} | ${c.feature} | ${tierOf(c)} | ${c.tied.join(', ')} | ${c.reason.split(' + ')[1] ?? ''} |`),
		'',
		'## No primary feature',
		'',
		'| API | Kind | Breadcrumb fallback |',
		'| --- | --- | --- |',
		...rows.filter(([, c]) => !c.feature).map(([n, c]) => `| ${n} | ${c.kind} | ${fallback(c)} |`),
		'',
		'## All choices',
		'',
		'| API | Kind | Primary feature | Reason |',
		'| --- | --- | --- | --- |',
		...rows.map(([n, c]) => `| ${n} | ${c.kind} | ${c.feature ? `${title.get(c.feature)} (${c.feature})` : `— (${fallback(c)})`} | ${c.reason} |`),
		'',
	];
	const file = new URL('data/reports/primary-features.md', root);
	if (check) {
		if (!existsSync(file) || readFileSync(file, 'utf-8') !== L.join('\n')) {
			console.error(`${fileURLToPath(file)} is out of date: run node scripts/primary-features.mjs`);
			process.exit(1);
		}
		return;
	}
	writeFileSync(file, L.join('\n'));
	console.log(`wrote ${fileURLToPath(file)}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const i = process.argv.indexOf('--json');
	if (i >= 0) process.stdout.write(JSON.stringify(computeAll(process.argv[i + 1]).out));
	else report(process.argv.includes('--check'));
}
